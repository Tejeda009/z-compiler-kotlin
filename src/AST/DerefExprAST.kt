/**
 * `*p`: the value a pointer points at.
 */
class DerefExprAST(pointer: ExprAST) : ExprAST() {
    private val pointer: ExprAST

    init {
        this.pointer = pointer
    }

    /** @return the pointer being read through
     */
    fun pointer(): ExprAST? {
        return pointer
    }

    /** @return the type pointed at, or null when `pointer` is not a typed pointer
     */
    fun elementType(builder: IRBuilder?): TypeRef? {
        return pointer.type(builder).elementType()
    }

    override fun type(builder: IRBuilder?): TypeRef {
        val elem: TypeRef? = elementType(builder)
        return if (elem == null) ZType.PTR else elem
    }

    override fun codeGen(builder: IRBuilder): LLVMTextUnit? {
        val p: LLVMTextUnit? = pointer.codeGen(builder)
        if (p == null) return null
        val elem: TypeRef? = p.type.elementType()
        if (elem == null) {
            logger.error("Error: '*' needs a typed pointer, got {}", p.type.zName())
            builder.markFailed()
            return null
        }
        val reg: String = builder.nextRegister()
        builder.appendLine(reg + " = load " + elem.llvm() + ", ptr " + p.text)
        builder.setRegisterType(reg, elem.llvm())
        return LLVMTextUnit(reg, elem)
    }

    companion object {
        private val logger: org.slf4j.Logger = org.slf4j.LoggerFactory.getLogger(DerefExprAST::class.java)
    }
}